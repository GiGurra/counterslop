// glyph(ch): the seven rows of ch (upper-cased; "?" for one it lacks).
export const glyph = (ch) => G[ch.toUpperCase()] || G["?"];

// glyphRects(ch): ch as few rectangles as the greedy merge finds: each row's
// runs of lit dots, grown down over the rows below that repeat the run.
// [{x, y, w, h}] in dots, y down from the top row.
const rectCache = new Map();
export function glyphRects(ch) {
  const key = ch.toUpperCase();
  if (rectCache.has(key)) return rectCache.get(key);
  const rows = glyph(key), used = rows.map(() => Array(FONT_W).fill(false)), out = [];
  for (let y = 0; y < FONT_H; y++) {
    for (let x = 0; x < FONT_W; x++) {
      if (rows[y][x] !== "#" || used[y][x]) continue;
      let w = 1;
      while (x + w < FONT_W && rows[y][x + w] === "#" && !used[y][x + w]) w++;
      let h = 1;
      const runAt = (yy) => { for (let i = 0; i < w; i++) if (rows[yy][x + i] !== "#" || used[yy][x + i]) return false; return (x + w >= FONT_W || rows[yy][x + w] !== "#") && (x === 0 || rows[yy][x - 1] !== "#"); };
      while (y + h < FONT_H && runAt(y + h)) h++;
      for (let yy = y; yy < y + h; yy++) for (let i = 0; i < w; i++) used[yy][x + i] = true;
      out.push({ x, y, w, h });
    }
  }
  rectCache.set(key, out);
  return out;
}

